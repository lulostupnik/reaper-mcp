"""The ReaScript functions the live tests call, typed: the server's surface
plus the few the tests use only to read REAPER's state back."""

from typing import Protocol, cast

from reapy import reascript_api

from reaper_mcp.reaper import Pointer, ReaScriptAPI


class LiveReaScriptAPI(ReaScriptAPI, Protocol):
    def EnumProjExtState(
        self, _project: int, _extname: str, _index: int, _key: str, _key_size: int,
        _value: str, _value_size: int, /,
    ) -> list: ...
    def DeleteProjectMarkerByIndex(self, _project: int, _index: int, /) -> bool: ...
    def DeleteTempoTimeSigMarker(self, _project: int, _index: int, /) -> bool: ...
    def TimeMap_QNToTime(self, _qn: float, /) -> float: ...
    def MIDI_CountEvts(self, _take: Pointer, _notes: int, _ccs: int, _sysex: int, /) -> list: ...
    def MIDI_GetNote(
        self, _take: Pointer, _index: int, _selected: int, _muted: int, _start: float,
        _end: float, _channel: int, _pitch: int, _velocity: int, /,
    ) -> list: ...
    def MIDI_GetProjTimeFromPPQPos(self, _take: Pointer, _ppq: float, /) -> float: ...
    def EnumProjects(self, _index: int, _path: str, _size: int, /) -> list: ...
    def IsProjectDirty(self, _project: int, /) -> int: ...
    def MarkProjectDirty(self, _project: int, /) -> None: ...
    def CountEnvelopePoints(self, _envelope: str, /) -> int: ...
    def SelectProjectInstance(self, _project: str, /) -> None: ...
    def GetTrackGUID(self, _track: str, /) -> str: ...
    def GetTrackMediaItem(self, _track: str, _index: int, /) -> str: ...
    def SetMediaItemSelected(self, _item: str, _selected: bool, /) -> None: ...
    def GetParentTrack(self, _track: str, /) -> str: ...
    def SelectAllMediaItems(self, _project: int, _selected: bool, /) -> None: ...
    def TrackFX_SetParam(self, _track: str, _fx: int, _param: int, _value: float, /) -> bool: ...
    def TrackFX_AddByName(
        self, _track: str, _name: str, _input_fx: bool, _instantiate: int, /
    ) -> int: ...
    def GetProjectName(self, _project: int, _buf: str, _size: int, /) -> list: ...
    def TrackFX_GetCount(self, _track: str, /) -> int: ...
    def TrackFX_GetNumParams(self, _track: str, _fx: int, /) -> int: ...
    def TrackFX_GetParamNormalized(self, _track: str, _fx: int, _param: int, /) -> float: ...
    def Undo_OnStateChangeEx2(
        self, _project: int, _name: str, _flags: int, _track: int, /
    ) -> None: ...


RPR = cast(LiveReaScriptAPI, reascript_api)
